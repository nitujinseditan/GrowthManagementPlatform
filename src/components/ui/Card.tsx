// 向后兼容：旧版单元素 Card API (hover + 普通 children)
// 逐步迁移到 shadcn compound Card API
// ═══════════════════════════════════════════

interface LegacyCardProps extends React.HTMLAttributes<HTMLDivElement> {
  hover?: boolean;
}

const LegacyCard = React.forwardRef<HTMLDivElement, LegacyCardProps>(
  ({ hover, className, children, ...props }, ref) => (
    <Card
      ref={ref}
      className={cn(
        "p-5",
        hover &&
          "cursor-pointer transition-all duration-300 hover:shadow-lg hover:-translate-y-1",
        className
      )}
      {...props}
    >
      {children}
    </Card>
  )
);
LegacyCard.displayName = "LegacyCard";

export default LegacyCard;
